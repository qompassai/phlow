#!/usr/bin/env python3
"""PH-2/PH-5 corpus harness (rung 3).

Runs the tasks in tasks.json through phlow, one at a time, against
the seat workspace (analysis) or a scratch clone of it (code_fix),
and records a draft manifest: one JSON line per completed run with
the run's outcome id, its pre-registered class/split/reviewer, and
its ground truth where the truth rule is mechanical. Analysis truth
is labelled later by a human verifier reading the saved digests;
this harness never invents it.

Usage:
    run_corpus.py --work DIR --tasks tasks.json --setup
    run_corpus.py --work DIR --tasks tasks.json --verify-plants
    run_corpus.py --work DIR --tasks tasks.json [--only ID ...]
                  [--limit N]

Work dir layout (all state lives here or in the config dir):
    configs/    generated phlow configs (also the outcome store's
                home: the CLI derives feedback.db from the config
                file's directory, so the corpus gets its own store)
    reports/    one .report.json + .digest.txt per run
    manifest-draft.jsonl

Bounds: at most TASKS_MAX tasks, RUN_TIMEOUT_S per run,
COURTESY_WAITS_MAX GPU-courtesy waits per run. The harness invokes
phlow only; it never runs cargo and never edits the seat tree.
"""

import argparse
import json
import os
import sqlite3
import subprocess
import sys
import time
import urllib.request

TASKS_MAX = 64
RUN_TIMEOUT_S = 1500
COURTESY_WAITS_MAX = 10
COURTESY_WAIT_S = 60
GPU_BUSY_PERCENT = 70
ROSE_PS_URL = "http://127.0.0.1:11434/api/ps"
PHLOW_BIN = "/home/phaedrus/.local/bin/phlow"
FLEET_CHECKS = "/home/phaedrus/.local/share/pax/repos/phlow/tools/fleet-checks"
SEAT_FREEZE = "/home/phaedrus/.config/phlow/freezes/torogao-ph10.tree.json"
CORPUS_FREEZE = "/home/phaedrus/.config/phlow/freezes/torogao-corpus-rung3.tree.json"

PLANNER_MODEL = "hf-gpt-oss-20b-tools-64k"
CODER_MODEL = "hf-devstral-24b-tools-64k"


class HarnessError(Exception):
    """A precondition failed; the run was not started or not trusted."""


def parse_args(argv):
    parser = argparse.ArgumentParser(prog="run_corpus")
    parser.add_argument("--work", required=True)
    parser.add_argument("--tasks", required=True)
    parser.add_argument("--seat", required=True)
    parser.add_argument("--scratch", default=None)
    parser.add_argument("--setup", action="store_true")
    parser.add_argument("--verify-plants", action="store_true")
    parser.add_argument("--only", nargs="*", default=None)
    parser.add_argument("--limit", type=int, default=None)
    args = parser.parse_args(argv)
    return args


def load_tasks(path):
    with open(path, "r", encoding="utf-8") as handle:
        data = json.load(handle)
    tasks = data["tasks"]
    if len(tasks) > TASKS_MAX:
        raise HarnessError(f"too many tasks: {len(tasks)} > {TASKS_MAX}")
    return data["reviewer_models"], tasks


